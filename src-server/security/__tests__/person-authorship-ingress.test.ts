/**
 * #4827 fix round 2: a turn is the person's only when Station marked it
 * `authoredBy: 'person'` (`services/orchestration/turn-authorship.ts`). The
 * mark is positive, so an ingress nobody classified is already not the
 * person: nothing marks it. What must never change unreviewed is WHO can
 * mark. This pins three things, and fails on any new one:
 *
 * 1. Where the mark is decided: `personTypedRequest` is called only at the
 *    three composer seams in the orchestration routes.
 * 2. Which files carry or read the mark (`personAuthored` / `authoredBy`).
 * 3. Every source file that starts or steers a turn, with its
 *    classification, so a new turn ingress needs one written down here.
 *
 * Limits: this is a syntactic scan of `src-server` for known dispatch call
 * shapes. It cannot see a turn started through a call shape it does not
 * list, and it pins files, not individual call sites inside a listed file.
 * The behaviour itself is proven by the route and end-to-end tests
 * (`person-authored-ingress.routes.test.ts`, `guardian-person-intent.test.ts`,
 * `turn-authorship.test.ts`).
 */

const ROOT = join(import.meta.dirname, '..', '..', '..');
const SERVER = join(ROOT, 'src-server');

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === '__tests__' || entry.name === 'node_modules') continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...sourceFiles(path));
    else if (
      entry.name.endsWith('.ts') &&
      !entry.name.endsWith('.test.ts') &&
      !entry.name.endsWith('.d.ts')
    )
      out.push(path);
  }
  return out;
}

/**
 * A generated file (`// Generated by …` header, e.g. the shipped docs
 * content `docs:mcp:generate` writes from Markdown) is static data that
 * quotes the documentation; it can neither decide nor carry the mark, so a
 * mention there is prose, not a producer.
 */
const GENERATED_HEADER = /^\/\/ Generated by /;

const FILES = sourceFiles(SERVER)
  .map((path) => ({
    path: relative(ROOT, path),
    text: readFileSync(path, 'utf8'),
  }))
  .filter((file) => !GENERATED_HEADER.test(file.text));

const filesMatching = (pattern: RegExp) =>
  FILES.filter((file) => pattern.test(file.text))
    .map((file) => file.path)
    .sort();

