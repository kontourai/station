const TURN_DISPATCH =
  /type: 'sendTurn'|type: 'steerTurn'|'steerTurn' as const|'sendTurn' as const|continueAsRecordedActor\(|continueExecutionTargetMessage\(|executeExecutionTargetMessage\(|executeForegroundMessage\(|submitSteer\(|dispatchWithReceipt\(|orchestrationService\.dispatch\(|orchestration\.dispatch\(|sessions\.dispatch\(|deps\.dispatch\(\{|\.submit\(\{/;

describe('who may mark a turn as the person (#4827)', () => {
  test('the mark is decided only at the three composer seams', () => {
    const callers = FILES.filter(
      (file) =>
        file.path !== 'src-server/security/person-authorship.ts' &&
        /personTypedRequest\(/.test(file.text),
    );
    expect(callers.map((file) => file.path)).toEqual([
      'src-server/routes/orchestration/orchestration.ts',
    ]);
    // /chat (composer), /conversations/:id/inbox, /commands steerTurn.
    expect(callers[0]!.text.match(/personTypedRequest\(/g)).toHaveLength(3);
  });

  test('only reviewed files carry or read the mark', () => {
    expect(filesMatching(/\b(personAuthored|authoredBy)\b/)).toEqual(
      [
        'src-server/routes/orchestration/orchestration.ts',
        'src-server/runtime/routes/conversation-start-ports.ts',
        'src-server/runtime/routes/runtime-routes.ts',
        'src-server/security/person-authorship.ts',
        'src-server/services/approvals/guardian-conversation.ts',
        'src-server/services/execution-target/execution-target-execution.ts',
        'src-server/services/orchestration/client-origin-propagation.ts',
        'src-server/services/orchestration/event-store.ts',
        'src-server/services/orchestration/orchestration-service.ts',
        'src-server/services/orchestration/thread-inbox.ts',
        'src-server/services/orchestration/turn-authorship.ts',
        'src-server/tools/station-control-delegation.ts',
      ].sort(),
    );
  });

  test('every file that starts or steers a turn has a classification', () => {
    expect(filesMatching(TURN_DISPATCH)).toEqual(
      Object.keys(TURN_INGRESS).sort(),
    );
    const marking = Object.entries(TURN_INGRESS)
      .filter(([, [kind]]) => kind === 'marks-person-composer-only')
      .map(([path]) => path);
    expect(marking).toEqual([
      'src-server/routes/orchestration/orchestration.ts',
    ]);
  });
});
