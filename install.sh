sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{ print $1 }'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | awk '{ print $1 }'
  else
    fail 'sha256sum or shasum is required'
  fi
}

# The <os>-<arch> of this host, spelled as Node.js does (process.platform and
# process.arch), so it names a prebuilt archive target and a pinned Node.js.
host_target() {
  case "$(uname -s)" in
    Darwin) host_os=darwin ;;
    Linux) host_os=linux ;;
    *) fail "unsupported operating system: $(uname -s)" ;;
  esac
  case "$(uname -m)" in
    x86_64|amd64) host_arch=x64 ;;
    arm64|aarch64) host_arch=arm64 ;;
    *) fail "unsupported processor architecture: $(uname -m)" ;;
  esac
  # A shell translated by Rosetta reports x86_64 on Apple silicon.
  if [ "$host_os" = darwin ] && [ "$host_arch" = x64 ] && \
    [ "$(sysctl -n sysctl.proc_translated 2>/dev/null || true)" = 1 ]; then
    host_arch=arm64
  fi
  printf '%s-%s\n' "$host_os" "$host_arch"
}

