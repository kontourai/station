# `node` is the one portable authority for resolving filesystem aliases and
# for verifying a signed manifest, so it is settled before anything else. A
# prebuilt archive brings its own Node.js to RUN Station, but that Node.js
# cannot vouch for the manifest that names it. In order of preference:
#   host     a Node.js on PATH, MINIMUM_VERIFIER_NODE_MAJOR or newer;
#   installed  the Node.js inside this channel's installed archive, verified
#            when it was installed (it is what the launcher already runs), so
#            `station upgrade` and uninstall need no host Node.js and no
#            download;
#   pinned   the official Node.js distribution pinned above by sha256,
#            downloaded into the private temporary directory and used only to
#            verify and extract. Only uninstall and the public-manifest path
#            (which can install a prebuilt archive) download it.
# A source release is different: it is built on this host and later run by
# the host Node.js, so that path requires the host Node.js 24 (checked below).
node_is_adequate() {
  node_probe_major="$("$1" -p 'process.versions.node.split(".")[0]' 2>/dev/null)" || return 1
  case "$node_probe_major" in ''|*[!0-9]*) return 1 ;; esac
  [ "$node_probe_major" -ge "$MINIMUM_VERIFIER_NODE_MAJOR" ]
}

download_pinned_node() {
  node_target="$(host_target)"
  pinned_node_distribution "$node_target" || \
    fail "no pinned Node.js distribution for $node_target; install Node.js $MINIMUM_VERIFIER_NODE_MAJOR or newer and rerun"
  require_command curl
  require_command tar
  node_distribution="$tmp_root/$pinned_node_file"
  printf 'Downloading Node.js %s to verify this install (no Node.js %s or newer on PATH)...\n' \
    "$PINNED_NODE_VERSION" "$MINIMUM_VERIFIER_NODE_MAJOR"
  curl -fsSL --retry 3 --retry-connrefused --connect-timeout 10 -o "$node_distribution" -- \
    "$PINNED_NODE_ORIGIN$pinned_node_file" || fail "could not download $pinned_node_file"
  [ "$(sha256_of "$node_distribution")" = "$pinned_node_sha256" ] || \
    fail "$pinned_node_file does not match its pinned sha256"
  node_directory="${pinned_node_file%.tar.gz}"
  mkdir -m 700 "$tmp_root/node"
  tar -xzf "$node_distribution" -C "$tmp_root/node" "$node_directory/bin/node" || \
    fail "could not extract $pinned_node_file"
  rm -f "$node_distribution"
  PATH="$tmp_root/node/$node_directory/bin:$PATH"
  export PATH
  node_is_adequate node || fail "the pinned Node.js $PINNED_NODE_VERSION does not run on this host"
}

