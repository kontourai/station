#!/usr/bin/env node
// Rebuilds the vendored libghostty-vt WebAssembly module from the pinned
// Ghostty revision. Station's terminal view loads only the committed output;
// this script exists so anyone can reproduce and review that binary.
//
//   node scripts/ghostty-vt/build-wasm.mjs --ghostty <checkout> --zig <zig>
//
// The Ghostty checkout must be exactly the pinned commit with a clean tree,
// and the Zig binary must report the pinned version. Download Zig from the
// official tarball listed in ZIG_RELEASES and verify it before use; this
// script refuses an unknown or mismatched toolchain rather than guessing.

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { invokedDirectly } from '../lib/module-entry.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const vendorDir = join(
  root,
  'packages/sdk/src/terminal-view/vendor/ghostty-vt',
);

/** Ghostty v1.4.0 (annotated tag ce787fc1 peels to this commit). */
const GHOSTTY_TAG = 'v1.4.0';
const GHOSTTY_REVISION = '83fb95624b0439ee660c2679b43b38c8b63769cd';
const ZIG_VERSION = '0.17.0';
/**
 * Official Zig 0.17.0 archives (https://ziglang.org/download/index.json).
 * Each archive is also signed with Zig's minisign key
 * RWSGOq2NVecA2UPNdBUZykf1CCb147pkmdtYxgb3Ti+JO/wCYvhbAb/U.
 */
const ZIG_RELEASES = {
  'x86_64-windows': {
    url: 'https://ziglang.org/download/0.17.0/zig-x86_64-windows-0.17.0.zip',
    sha256: 'b5663f69581dcf391293fbf16c06cb80d81d806545ce618b4d0bab7f0eb8c428',
  },
};
/**
 * Images (Kitty graphics) are deferred and Station does not serialize
 * terminal state (snapshot), so the module omits both. Every other feature
 * stays at Ghostty's default.
 */
const BUILD_ARGS = [
  'build',
  '-Demit-lib-vt',
  '-Dtarget=wasm32-freestanding',
  '-Doptimize=ReleaseSmall',
  '-Dvt-features=-kitty_graphics,-snapshot',
];

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    encoding: 'utf8',
    windowsHide: true,
    maxBuffer: 64 * 1024 * 1024,
    ...options,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `${command} ${args.join(' ')} exited ${result.status}\n${result.stdout}\n${result.stderr}`,
    );
  }
  // stdout is null when the caller inherits stdio (the zig build itself).
  return (result.stdout ?? '').trim();
}

/**
 * GhosttyKey follows the W3C UI Events `code` list in header order. Emits
 * the `code` → enum value table so the view never hand-copies the enum.
 */
function keyTableSource(eventHeader) {
  const end = eventHeader.indexOf('} GhosttyKey;');
  const start = eventHeader.lastIndexOf('typedef enum', end);
  if (end < 0 || start < 0) throw new Error('GhosttyKey enum not found');
  const body = eventHeader.slice(start, end);
  const names = [
    ...body.matchAll(/^\s*GHOSTTY_KEY_([A-Z0-9_]+)(\s*=\s*[^,]+)?,/gm),
  ]
    .filter(([, name]) => name !== 'MAX_VALUE')
    .map(([, name, explicit], index) => {
      if (explicit && !(index === 0 && /=\s*0$/.test(explicit.trim())))
        throw new Error(`Unexpected explicit value for GHOSTTY_KEY_${name}`);
      return name;
    });
  if (names[0] !== 'UNIDENTIFIED')
    throw new Error('GhosttyKey must start at UNIDENTIFIED');
  const pascal = (name) =>
    name
      .split('_')
      .map((part) => part.charAt(0) + part.slice(1).toLowerCase())
      .join('');
  const code = (name) => (/^[A-Z]$/.test(name) ? `Key${name}` : pascal(name));
  const rows = names
    .slice(1)
    .map((name, index) => `  ${code(name)}: ${index + 1},`)
    .join('\n');
  return [
    '// Generated by scripts/ghostty-vt/build-wasm.mjs from',
    `// include/ghostty/vt/key/event.h at Ghostty ${GHOSTTY_REVISION}.`,
    '// Do not edit: rerun the build script.',
    '',
    '/** W3C `KeyboardEvent.code` → `GhosttyKey`. */',
    'export const GHOSTTY_KEY_BY_CODE: Readonly<Record<string, number>> = {',
    rows,
    '};',
    '',
  ].join('\n');
}

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

async function main() {
  const { values } = parseArgs({
    options: {
      ghostty: { type: 'string' },
      zig: { type: 'string', default: 'zig' },
      'cache-dir': { type: 'string' },
    },
  });
  if (!values.ghostty) throw new Error('--ghostty <checkout> is required');
  const ghostty = resolve(values.ghostty);

  const head = run('git', ['-C', ghostty, 'rev-parse', 'HEAD']);
  if (head !== GHOSTTY_REVISION)
    throw new Error(
      `Ghostty checkout is ${head}, expected ${GHOSTTY_REVISION}`,
    );
  const dirty = run('git', ['-C', ghostty, 'status', '--porcelain']);
  if (dirty) throw new Error(`Ghostty checkout is not clean:\n${dirty}`);
  // Git for Windows defaults to core.autocrlf=true, which rewrites text files
  // without an eol attribute: the build input would no longer be the pinned
  // commit's bytes, and `git status` does not show that conversion.
  const converted = run('git', ['-C', ghostty, 'ls-files', '--eol'])
    .split('\n')
    .filter((line) => /^i\/lf\s+w\/crlf\b/.test(line));
  if (converted.length)
    throw new Error(
      `${converted.length} Ghostty files were checked out with CRLF line endings. ` +
        'Check out with `git -c core.autocrlf=false` so the build reads the commit’s bytes.',
    );

  const zigVersion = run(values.zig, ['version']);
  if (zigVersion !== ZIG_VERSION) {
    const archives = Object.entries(ZIG_RELEASES)
      .map(([host, { url, sha256 }]) => `  ${host}: ${url} (sha256 ${sha256})`)
      .join('\n');
    throw new Error(
      `zig reports ${zigVersion}, expected ${ZIG_VERSION}. Official archives:\n${archives}`,
    );
  }

  const env = { ...process.env };
  if (values['cache-dir']) env.ZIG_GLOBAL_CACHE_DIR = values['cache-dir'];
  run(values.zig, BUILD_ARGS, { cwd: ghostty, env, stdio: 'inherit' });

  mkdirSync(vendorDir, { recursive: true });
  const wasmOut = join(vendorDir, 'ghostty-vt.wasm');
  copyFileSync(join(ghostty, 'zig-out/bin/ghostty-vt.wasm'), wasmOut);
  copyFileSync(join(ghostty, 'LICENSE'), join(vendorDir, 'LICENSE'));

  // The type manifest the module reports about itself: the layout test
  // compares Station's hand-written struct offsets against this file, and a
  // second test proves this file still matches the committed binary.
  const { instance } = await WebAssembly.instantiate(readFileSync(wasmOut), {
    env: new Proxy({}, { get: () => () => 0 }),
  });
  const exports = instance.exports;
  const ptr = exports.ghostty_type_json();
  const bytes = new Uint8Array(exports.memory.buffer);
  let end = ptr;
  while (bytes[end] !== 0) end += 1;
  const json = JSON.parse(new TextDecoder().decode(bytes.subarray(ptr, end)));
  writeFileSync(
    join(vendorDir, 'types.json'),
    `${JSON.stringify(json, null, 2)}\n`,
  );

  writeFileSync(
    join(root, 'packages/sdk/src/terminal-view/engine/keys.generated.ts'),
    keyTableSource(
      readFileSync(join(ghostty, 'include/ghostty/vt/key/event.h'), 'utf8'),
    ),
  );

  writeFileSync(
    join(vendorDir, 'REVISION'),
    [
      `ghostty ${GHOSTTY_TAG} ${GHOSTTY_REVISION}`,
      `zig ${ZIG_VERSION}`,
      `args ${BUILD_ARGS.slice(1).join(' ')}`,
      `sha256 ${sha256(wasmOut)}`,
      '',
    ].join('\n'),
  );
  process.stdout.write(`${sha256(wasmOut)}  ghostty-vt.wasm\n`);
}

if (invokedDirectly(import.meta.url)) {
  await main();
}
