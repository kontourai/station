import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { build } from 'esbuild';
import { BASIS_MCP_APP_MANIFEST } from './basis-mcp-app-manifest.mjs';

const root = resolve(import.meta.dirname, '..');
const REPAIR_COMMAND = 'npm run basis:mcp:generate';

export function biomeFormatterInvocation(
  projectRoot,
  output,
  nodeExecutable = process.execPath,
) {
  return {
    command: nodeExecutable,
    args: [
      resolve(projectRoot, 'node_modules/@biomejs/biome/bin/biome'),
      'format',
      `--stdin-file-path=${resolve(projectRoot, output)}`,
    ],
  };
}

async function buildOnce(app) {
  const result = await build({
    entryPoints: [resolve(root, app.entry)],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    minify: true,
    write: false,
    target: ['es2022'],
    legalComments: 'none',
  });
  const generated = `// Generated by scripts/generate-basis-mcp-apps.mjs. Do not edit.\n// biome-ignore lint/suspicious/noTemplateCurlyInString: the compiled program is serialized data, not an interpolated host template.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`;
  const formatter = biomeFormatterInvocation(root, app.output);
  return execFileSync(formatter.command, formatter.args, {
    input: generated,
    encoding: 'utf8',
    maxBuffer: 2 * 1024 * 1024,
    cwd: root,
    windowsHide: true,
  });
}

const STALE_CONTEXT_BYTES = 48;

function digest(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function escapedBytes(bytes) {
  return [...bytes]
    .map((byte) =>
      byte >= 0x20 && byte <= 0x7e && byte !== 0x5c
        ? String.fromCharCode(byte)
        : `\\x${byte.toString(16).padStart(2, '0')}`,
    )
    .join('');
}

function staleGeneratedDiagnostic(output, actual, expected) {
  const actualBytes = Buffer.from(actual);
  const expectedBytes = Buffer.from(expected);
  const common = Math.min(actualBytes.length, expectedBytes.length);
  let difference = 0;
  while (
    difference < common &&
    actualBytes[difference] === expectedBytes[difference]
  )
    difference += 1;
  const from = Math.max(0, difference - STALE_CONTEXT_BYTES);
  const to = Math.min(
    Math.max(actualBytes.length, expectedBytes.length),
    difference + STALE_CONTEXT_BYTES,
  );
  return [
    `Generated Basis MCP app is stale: ${output}`,
    `actual: ${actualBytes.length} bytes sha256 ${digest(actualBytes)}`,
    `expected: ${expectedBytes.length} bytes sha256 ${digest(expectedBytes)}`,
    `first differing byte: ${difference}`,
    `actual context [${from},${to}): ${escapedBytes(actualBytes.subarray(from, to))}`,
    `expected context [${from},${to}): ${escapedBytes(expectedBytes.subarray(from, to))}`,
    '',
    'Repair with:',
    `  ${REPAIR_COMMAND}`,
  ].join('\n');
}

/**
 * @param {{
 *   manifest?: readonly { id: string, entry: string, output: string }[],
 *   check?: boolean,
 *   buildApp?: (app: { id: string, entry: string, output: string }) => Promise<string>,
 *   read?: (path: string) => Promise<string>,
 *   write?: (path: string, text: string) => Promise<unknown>,
 * }} options
 */
export async function generateBasisMcpApps(options = {}) {
  const {
    manifest = BASIS_MCP_APP_MANIFEST,
    check = false,
    buildApp = buildOnce,
    read = (path) => readFile(path, 'utf8'),
    write = (path, text) => writeFile(path, text),
  } = options;
  for (const app of manifest) {
    const first = await buildApp(app);
    const second = await buildApp(app);
    if (first !== second)
      throw new Error(
        `Non-deterministic Basis MCP app build for ${app.id}; two in-memory builds differ.`,
      );
    const output = resolve(root, app.output);
    if (!check) {
      await write(output, first);
      continue;
    }
    const actual = await read(output);
    if (actual !== first)
      throw new Error(staleGeneratedDiagnostic(app.output, actual, first));
  }
}

if (resolve(process.argv[1] ?? '') === import.meta.filename)
  await generateBasisMcpApps({ check: process.argv.includes('--check') });
