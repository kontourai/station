/**
 * One GitHub tracking issue per scheduled sweep (#2923): found by its exact
 * title and its author, created only when something is outstanding, updated
 * while anything is, and closed as completed once nothing is. The sweeps
 * never fail a required check; this issue is how their findings stay visible.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSyncBounded } from './bounded-capture.mjs';

/**
 * GitHub's issue body cap. Reports are built to stay below 60,000 characters;
 * neutralizing can lengthen them, and the posted text is what must fit.
 */
export const TRACKING_BODY_LIMIT = 65_536;

/**
 * The login GitHub gives an issue created with a workflow's GITHUB_TOKEN
 * (checked on #2953, the documentation sweep's tracker). Anyone can open an
 * issue with a tracker's title, so only an issue this identity wrote counts.
 */
const TRACKING_ISSUE_AUTHOR = 'github-actions[bot]';

/**
 * Text a sweep posts is generated by our scripts from paths, issue numbers
 * and label names: plain Markdown with no intended mention or HTML entity.
 * The report file, though, comes from a job that runs installed third-party
 * code, so the posted copy breaks every way that text could still notify
 * someone: each `@` gets a zero-width space after it, and each `&` that
 * could start an HTML entity (`&#64;`, `&#x40;`, `&commat;`) is escaped,
 * since GitHub decodes entities before it looks for mentions. HTML comments
 * and links are left as they are: neither notifies once no `@` survives.
 * Escaping `&` can show `&amp;` inside a code span; the reports carry none.
 */
function neutralizeReport(body) {
  return body
    .replace(/&(?=[#A-Za-z])/g, '&amp;')
    .replace(/@(?=[A-Za-z0-9_-])/g, '@\u200b');
}

/**
 * Write the copy of a report to post and return its path. The size bound
 * applies to that posted text, after neutralizing, so a body that grows past
 * it is refused here with a clear error rather than by GitHub; it is never
 * truncated.
 * @param {string} reportPath
 * @param {{ limit?: number }} [options]
 */
export function postableReport(
  reportPath,
  { limit = TRACKING_BODY_LIMIT } = {},
) {
  const posted = neutralizeReport(readFileSync(reportPath, 'utf8'));
  if (posted.length > limit)
    throw new Error(
      `report is ${posted.length} characters to post; refusing to post more than ${limit}`,
    );
  const path = `${reportPath}.postable`;
  writeFileSync(path, posted);
  return path;
}

/**
 * Refuse a report that does not describe the revision this job checked out.
 * This proves the report is current, not who produced it: code in the job
 * that wrote it can stamp any revision it likes.
 * @param {string} revision the report's recorded revision
 * @param {string} head this checkout's revision
 */
export function assertReportRevision(revision, head) {
  if (revision !== head)
    throw new Error(
      `report describes ${revision}, but this checkout is ${head}; refusing to post it`,
    );
}

export function runGh(args) {
  return execFileSyncBounded('gh', args, {
    encoding: 'utf8',
    windowsHide: true,
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

/**
 * @param {{ repo: string, reportPath: string, title: string, labels: readonly string[], outstanding: number, gh?: (args: string[]) => string }} input
 * @returns {{ action: 'none'|'created'|'updated'|'closed', number?: number }}
 */
export function upsertTrackingIssue({
  repo,
  reportPath,
  title,
  labels,
  outstanding,
  author = TRACKING_ISSUE_AUTHOR,
  gh = runGh,
}) {
  if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repo ?? ''))
    throw new Error('--repo must be owner/name');
  const numbers = gh([
    'api',
    '--method',
    'GET',
    // Found by its stable title, not a label, so relabelling the issue
    // cannot make the next sweep open a duplicate. Search matches words;
    // the exact title is checked in the filter.
    'search/issues',
    '-f',
    `q=repo:${repo} is:issue in:title "${title}"`,
    '-f',
    'per_page=100',
    '--jq',
    `.items[] | select(.pull_request == null and .title == ${JSON.stringify(title)}) | "\\(.number)\\t\\(.user.login)"`,
  ])
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split('\t'))
    // A same-titled issue someone else opened is ignored, so the sweep
    // writes only to an issue it created.
    .filter(([, login]) => login === author)
    .map(([number]) => Number(number))
    .sort((a, b) => a - b);
  const existing = numbers[0];
  if (existing === undefined) {
    if (!outstanding) return { action: 'none' };
    const created = gh([
      'api',
      '--method',
      'POST',
      `repos/${repo}/issues`,
      '-f',
      `title=${title}`,
      '-F',
      `body=@${reportPath}`,
      ...labels.flatMap((label) => ['-f', `labels[]=${label}`]),
      '--jq',
      '.number',
    ]);
    return { action: 'created', number: Number(created) };
  }
  gh([
    'api',
    '--method',
    'PATCH',
    `repos/${repo}/issues/${existing}`,
    '-F',
    `body=@${reportPath}`,
    '-f',
    `state=${outstanding ? 'open' : 'closed'}`,
    ...(outstanding ? [] : ['-f', 'state_reason=completed']),
    '--jq',
    '.number',
  ]);
  return { action: outstanding ? 'updated' : 'closed', number: existing };
}
