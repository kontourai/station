export const RELEASE_TAG_PATTERN =
  /^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-preview\.([1-9][0-9]*))?$/;

export function releaseVariants(tag) {
  if (!RELEASE_TAG_PATTERN.test(tag)) {
    throw new Error(`Invalid release artifact inventory: invalid tag ${tag}`);
  }
  const variants = [
    [
      'portable-server',
      'portable',
      'universal',
      'tar.gz',
      'distributable',
      'not-applicable',
      'not-applicable',
      'not-applicable',
      'not-applicable',
      ['station-portable.tar.gz'],
    ],
    [
      'macos-aarch64',
      'macos',
      'aarch64',
      'dmg',
      'distributable',
      'signed',
      'platform-signature',
      'signed',
      'tauri-updater-signature',
      [
        `station-${tag}-macos-aarch64.dmg`,
        `station-${tag}-macos-aarch64.app.tar.gz`,
        `station-${tag}-macos-aarch64.app.tar.gz.sig`,
      ],
    ],
    [
      'macos-x86_64',
      'macos',
      'x86_64',
      'dmg',
      'distributable',
      'signed',
      'platform-signature',
      'signed',
      'tauri-updater-signature',
      [
        `station-${tag}-macos-x86_64.dmg`,
        `station-${tag}-macos-x86_64.app.tar.gz`,
        `station-${tag}-macos-x86_64.app.tar.gz.sig`,
      ],
    ],
    [
      'windows-x86_64',
      'windows',
      'x86_64',
      'msi',
      'distributable',
      'signed',
      'platform-signature',
      'signed',
      'tauri-updater-signature',
      [
        `station-${tag}-windows-x86_64.msi`,
        `station-${tag}-windows-x86_64.msi.zip`,
        `station-${tag}-windows-x86_64.msi.zip.sig`,
      ],
    ],
    [
      'linux-x86_64',
      'linux',
      'x86_64',
      'appimage',
      'distributable',
      'not-applicable',
      'not-applicable',
      'signed',
      'tauri-updater-signature',
      [
        `station-${tag}-linux-x86_64.AppImage`,
        `station-${tag}-linux-x86_64.AppImage.tar.gz`,
        `station-${tag}-linux-x86_64.AppImage.tar.gz.sig`,
      ],
    ],
    [
      'android-universal-apk',
      'android',
      'universal',
      'apk',
      'distributable',
      'signed',
      'platform-signature',
      'not-applicable',
      'not-applicable',
      [`station-${tag}-android-universal.apk`],
    ],
    [
      'android-universal-aab',
      'android',
      'universal',
      'aab',
      'distributable',
      'signed',
      'platform-signature',
      'not-applicable',
      'not-applicable',
      [`station-${tag}-android-universal.aab`],
    ],
    [
      'ios-simulator',
      'ios',
      'aarch64',
      'tar.gz',
      'verification-only',
      'unsigned',
      'not-applicable',
      'not-applicable',
      'not-applicable',
      [`station-${tag}-ios-simulator.app.tar.gz`],
    ],
    [
      'ios-device',
      'ios',
      'aarch64',
      'ipa',
      'distributable',
      'signed',
      'platform-signature',
      'not-applicable',
      'not-applicable',
      [`station-${tag}-ios-device.ipa`],
    ],
  ].map(
    ([
      id,
      platform,
      architecture,
      packageType,
      distribution,
      platformSigningState,
      platformSigningProof,
      updaterSigningState,
      updaterSigningProof,
      files,
    ]) => ({
      id,
      platform,
      architecture,
      packageType,
      distribution,
      platformSigning: {
        state: platformSigningState,
        proof: platformSigningProof,
      },
      updaterSigning: {
        state: updaterSigningState,
        proof: updaterSigningProof,
      },
      files,
    }),
  );
  return tag.includes('-preview.')
    ? variants.filter((variant) => variant.platform !== 'ios')
    : variants;
}
