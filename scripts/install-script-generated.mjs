// Owns the generated blocks inside install.sh. install.sh must stay a single
// standalone file (`curl | sh`), so data that already has a source of truth is
// projected into marker-delimited blocks here instead of being hand-typed:
//
//   PINNED MANIFEST SIGNING KEYS  <- config/release-manifest-keys.json
//   CHANNEL CONSTANTS             <- config/channel-ports.json (channels +
//                                    releaseRings)
//   PORTABLE SERVER TARGETS       <- packages/shared/src/portable-server-targets.mjs
//   NODE RUNTIME PINS             <- config/portable-server-node-runtime.json
//
// `--sync` rewrites the blocks in place; `--check` fails when install.sh no
// longer matches what this script would write.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { PORTABLE_SERVER_TARGETS } from '../packages/shared/src/portable-server-targets.mjs';
import { CHANNEL_PORTS, RELEASE_RINGS } from './channel-ports.mjs';
import { invokedDirectly } from './lib/module-entry.mjs';

const root = resolve(import.meta.dirname, '..');
export const INSTALL_SCRIPT_PATH = resolve(root, 'install.sh');
const KEYS_PATH = resolve(root, 'config/release-manifest-keys.json');
const NODE_RUNTIME_PATH = resolve(
  root,
  'config/portable-server-node-runtime.json',
);
const GENERATOR = 'scripts/install-script-generated.mjs';

/** A single-quoted shell literal; refuses what a single quote cannot hold. */
function shellSingleQuoted(value) {
  if (value.includes("'"))
    throw new Error(`cannot embed a single quote in install.sh: ${value}`);
  return `'${value}'`;
}

function signingKeysBlock() {
  const keys = JSON.parse(readFileSync(KEYS_PATH, 'utf8'));
  return [
    `# Generated by ${GENERATOR} from config/release-manifest-keys.json`,
    '# (JSON.stringify of its content). Do not edit by hand.',
    `PINNED_MANIFEST_SIGNING_KEYS=${shellSingleQuoted(JSON.stringify(keys))}`,
  ];
}

function channelConstantsBlock() {
  const runtimeChannels = Object.values(RELEASE_RINGS).map(
    (ring) => ring.runtimeChannel,
  );
  const lines = [
    `# Generated by ${GENERATOR} from config/channel-ports.json.`,
    '# Do not edit by hand. RELEASE_RINGS_JSON is the installable ring table:',
    '# each ring, the runtime channel it installs as, and whether it is a',
    '# prerelease (tags vX.Y.Z-<ring>.N) or the one unlabelled ring (vX.Y.Z).',
    `INSTALLABLE_RUNTIME_CHANNELS=${shellSingleQuoted(runtimeChannels.join(' '))}`,
    `RELEASE_RINGS_JSON=${shellSingleQuoted(
      JSON.stringify(
        Object.fromEntries(
          Object.entries(RELEASE_RINGS).map(([ring, entry]) => [
            ring,
            {
              runtimeChannel: entry.runtimeChannel,
              prerelease: entry.prerelease,
            },
          ]),
        ),
      ),
    )}`,
    '# Sets the per-runtime-channel install constants; fails for a channel that',
    '# no installable ring installs as.',
    'channel_constants() {',
    '  case "$1" in',
  ];
  for (const [ring, entry] of Object.entries(RELEASE_RINGS)) {
    const ports = CHANNEL_PORTS[entry.runtimeChannel];
    lines.push(
      `    ${entry.runtimeChannel})`,
      `      runtime_release_channel=${ring}`,
      `      runtime_server_port=${ports.serverPort}`,
      `      runtime_ui_port=${ports.uiPort}`,
      `      runtime_launcher_name=${entry.launcher}`,
      '      ;;',
    );
  }
  lines.push('    *) return 1 ;;', '  esac', '}');
  return lines;
}

function portableServerTargetsBlock() {
  return [
    `# Generated by ${GENERATOR} from`,
    '# packages/shared/src/portable-server-targets.mjs. Do not edit by hand.',
    '# Every platform a prebuilt server archive is published for, and its format.',
    `PORTABLE_SERVER_TARGETS_JSON=${shellSingleQuoted(
      JSON.stringify(
        PORTABLE_SERVER_TARGETS.map(({ os, arch, format }) => ({
          os,
          arch,
          format,
        })),
      ),
    )}`,
  ];
}

const SHA256_HEX = /^[0-9a-f]{64}$/;
const SAFE_FILE = /^[A-Za-z0-9._-]+$/;

/**
 * The pinned official Node.js distributions install.sh may download to verify
 * and extract a release on a host without an adequate Node.js. Only the
 * tar.gz (POSIX) targets: Windows installs through install.ps1.
 */
function nodeRuntimePinsBlock() {
  const runtime = JSON.parse(readFileSync(NODE_RUNTIME_PATH, 'utf8'));
  const origin = new URL(runtime.origin);
  if (
    runtime.schemaVersion !== 1 ||
    !/^[0-9]+\.[0-9]+\.[0-9]+$/.test(runtime.version) ||
    origin.protocol !== 'https:' ||
    origin.href !== runtime.origin ||
    !origin.href.endsWith('/')
  )
    throw new Error(`${NODE_RUNTIME_PATH} has an unexpected shape`);
  const lines = [
    `# Generated by ${GENERATOR} from`,
    '# config/portable-server-node-runtime.json. Do not edit by hand. The official',
    '# Node.js distribution for each POSIX archive target, pinned by digest.',
    `PINNED_NODE_VERSION=${shellSingleQuoted(runtime.version)}`,
    `PINNED_NODE_ORIGIN=${shellSingleQuoted(origin.href)}`,
    '# Sets pinned_node_file and pinned_node_sha256 for <os>-<arch>; fails for a',
    '# target with no pinned tar.gz distribution.',
    'pinned_node_distribution() {',
    '  case "$1" in',
  ];
  for (const { os, arch, format } of PORTABLE_SERVER_TARGETS) {
    if (format !== 'tar.gz') continue;
    const id = `${os}-${arch}`;
    const entry = runtime.distributions?.[id];
    if (
      typeof entry?.file !== 'string' ||
      !SAFE_FILE.test(entry.file) ||
      !entry.file.endsWith('.tar.gz') ||
      !SHA256_HEX.test(entry.sha256 ?? '')
    )
      throw new Error(`${NODE_RUNTIME_PATH} has no pinned tar.gz for ${id}`);
    lines.push(
      `    ${id})`,
      `      pinned_node_file=${shellSingleQuoted(entry.file)}`,
      `      pinned_node_sha256=${entry.sha256}`,
      '      ;;',
    );
  }
  lines.push('    *) return 1 ;;', '  esac', '}');
  return lines;
}

const BLOCKS = [
  { name: 'PINNED MANIFEST SIGNING KEYS', render: signingKeysBlock },
  { name: 'CHANNEL CONSTANTS', render: channelConstantsBlock },
  { name: 'PORTABLE SERVER TARGETS', render: portableServerTargetsBlock },
  { name: 'NODE RUNTIME PINS', render: nodeRuntimePinsBlock },
];

function markers(name) {
  return {
    begin: `# BEGIN GENERATED ${name}\n`,
    end: `# END GENERATED ${name}\n`,
  };
}

/** install.sh's text with every generated block rendered from its source. */
export function renderInstallScript(text) {
  let output = text;
  for (const { name, render } of BLOCKS) {
    const { begin, end } = markers(name);
    const start = output.indexOf(begin);
    const stop = output.indexOf(end);
    if (
      start === -1 ||
      stop === -1 ||
      stop < start ||
      output.indexOf(begin, start + 1) !== -1 ||
      output.indexOf(end, stop + 1) !== -1
    )
      throw new Error(`install.sh must contain exactly one ${name} block`);
    output = `${output.slice(0, start + begin.length)}${render().join('\n')}\n${output.slice(stop)}`;
  }
  return output;
}

/** Throws when `path` differs from what `--sync` would write. */
export function checkInstallScript(path = INSTALL_SCRIPT_PATH) {
  const actual = readFileSync(path, 'utf8');
  if (renderInstallScript(actual) !== actual)
    throw new Error(
      `Generated install.sh blocks are stale: ${path}; run node ${GENERATOR} --sync`,
    );
}

export function syncInstallScript(path = INSTALL_SCRIPT_PATH) {
  const actual = readFileSync(path, 'utf8');
  const rendered = renderInstallScript(actual);
  if (rendered !== actual) writeFileSync(path, rendered);
}

// Compare real paths: import.meta.url is percent-encoded and symlink-resolved,
// so a raw `file://${argv[1]}` differs for a path with a space or a symlinked
// checkout, and --check would exit 0 without checking anything (#2682).
if (invokedDirectly(import.meta.url)) {
  if (process.argv[2] === '--sync') syncInstallScript();
  else if (process.argv[2] === '--check') checkInstallScript();
  else {
    process.stderr.write(`usage: node ${GENERATOR} --sync|--check\n`);
    process.exitCode = 1;
  }
}
