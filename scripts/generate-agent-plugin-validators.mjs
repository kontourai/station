import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  closeSync,
  mkdtempSync,
  openSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
export async function generateAgentPluginValidators({ check = false } = {}) {
  const sources = [
    'schemas/agent-plugins/1.0.0/plugin.schema.json',
    'schemas/agent-plugins/io.kontourai.station-1.0.schema.json',
  ];
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { source: true, esm: true },
  });
  const ids = sources.map((path) => {
    const schema = JSON.parse(readFileSync(join(root, path), 'utf8'));
    ajv.addSchema(schema);
    return schema.$id;
  });
  const source = standaloneCode(ajv, {
    validateManifest: ids[0],
    validateStationExtension: ids[1],
  });
  const bundled = await build({
    stdin: {
      contents: source,
      resolveDir: root,
      sourcefile: 'agent-plugin-validators.generated.mjs',
      loader: 'js',
    },
    bundle: true,
    write: false,
    platform: 'neutral',
    format: 'esm',
    target: 'es2022',
    logLevel: 'silent',
  });
  const provenance = sources
    .map(
      (path) =>
        `${path} sha256:${createHash('sha256')
          .update(readFileSync(join(root, path)))
          .digest('hex')}`,
    )
    .join('\n * ');
  const header = `// biome-ignore-all lint: Generated schema validation; edit the owning schemas and regenerate.\n/** Generated by scripts/generate-agent-plugin-validators.mjs.\n * Ajv ${require('ajv/package.json').version}; esbuild ${require('esbuild/package.json').version}.\n * ${provenance}\n */\n`;
  const runtimeLicense = readFileSync(
    join(dirname(require.resolve('ajv/package.json')), 'LICENSE'),
    'utf8',
  );
  const inputDirectory = mkdtempSync(
    join(tmpdir(), 'station-validator-format-'),
  );
  let inputFd;
  let output;
  try {
    const inputPath = join(inputDirectory, 'input.mjs');
    writeFileSync(
      inputPath,
      header +
        `/*! Bundled Ajv runtime helper.\n${runtimeLicense}*/\n` +
        bundled.outputFiles[0].text.replaceAll('\nexport {', '\n\nexport {'),
    );
    // Biome's Node launcher inherits stdin into another process. A regular
    // file has a definite EOF, avoiding a pipe kept open across that launch.
    inputFd = openSync(inputPath, 'r');
    output = execFileSync(
      process.execPath,
      [
        join(root, 'node_modules/@biomejs/biome/bin/biome'),
        'format',
        '--stdin-file-path=agent-plugin-validators.generated.mjs',
      ],
      {
        stdio: [inputFd, 'pipe', 'pipe'],
        encoding: 'utf8',
        windowsHide: true,
        timeout: 30_000,
      },
    );
  } finally {
    if (inputFd !== undefined) closeSync(inputFd);
    rmSync(inputDirectory, { recursive: true, force: true });
  }
  const target = join(
    root,
    'packages/shared/src/agent-plugin-validators.generated.mjs',
  );
  if (check) {
    if (readFileSync(target, 'utf8') !== output)
      throw new Error(
        'Agent Plugin validators are stale; run node scripts/generate-agent-plugin-validators.mjs',
      );
  } else writeFileSync(target, output);
}
if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url))
  await generateAgentPluginValidators({
    check: process.argv.includes('--check'),
  });
