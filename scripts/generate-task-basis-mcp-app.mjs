import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const entry = resolve(
  root,
  'packages/basis-pane/src/task-basis-mcp-app.browser.ts',
);
const output = resolve(
  root,
  'packages/basis-pane/src/task-basis-mcp-app.generated.ts',
);
const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  minify: true,
  write: false,
  target: ['es2022'],
  legalComments: 'none',
});
const generated = `// Generated by scripts/generate-task-basis-mcp-app.mjs. Do not edit.\n// biome-ignore lint/suspicious/noTemplateCurlyInString: the compiled program is serialized data, not an interpolated host template.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`;
// Apply the repository formatter in memory so generation and pre-push checking
// agree byte-for-byte without mutating unrelated files.
const source = execFileSync(
  resolve(root, 'node_modules/.bin/biome'),
  ['format', `--stdin-file-path=${output}`],
  {
    input: generated,
    encoding: 'utf8',
    maxBuffer: 2 * 1024 * 1024,
    cwd: root,
    windowsHide: true,
  },
);
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== source)
    throw new Error(
      'Task Basis MCP App bundle is stale; run node scripts/generate-task-basis-mcp-app.mjs',
    );
} else await writeFile(output, source);
