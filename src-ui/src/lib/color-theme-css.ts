/**
 * Renders the color-theme catalog into the two checked-in artifacts that put
 * a theme in force before the first paint (docs/decisions/user-color-themes.md):
 *
 * - `src-ui/src/color-themes.generated.css`, imported by `index.css` (every
 *   token) and, as `color-themes.startup.generated.css`, by the splash
 *   stylesheet (surfaces and text only, which is all the splash paints).
 * - the index block in `src-ui/public/startup-theme.js`, which validates the
 *   stored selection, stamps the root attributes and sets `theme-color`
 *   before any stylesheet or module loads.
 *
 * `npm run gen:color-themes` writes them; `color-theme-artifacts.test.ts`
 * regenerates and compares, so a hand edit or a stale artifact fails.
 *
 * ## Selectors and precedence
 *
 * The attributes live on `<html>`: `data-color-theme` (family),
 * `data-color-theme-flavor` (the resolved DARK flavor) and
 * `data-color-theme-accent` (the resolved accent). Light mode keys on
 * `data-theme="light"`; anything else is dark, as in the tokens.
 *
 * - Roles, Station variables, action and focus: `:root[family][flavor]` plus
 *   the mode, weight (0,4,0); a named accent adds one attribute (0,5,0). That
 *   outranks the tokens' and index.css's `:root`/`[data-theme]` blocks (0,1,0)
 *   and the channel blocks (up to 0,3,0), so the theme owns action and focus
 *   in a Dev, Beta or Nightly build too.
 * - Brand: `html[data-color-theme]:where(...)`, weight (0,1,1). It beats the
 *   (0,1,0) defaults but loses to the channel blocks (0,2,0 and up), and
 *   the per-flavor channel rules below (0,5,0) replace the channel colour
 *   with its shade for this flavor's surfaces. So a channel build keeps its
 *   identity on `--k-brand` alone.
 * - A white-label branding theme is inline style on `<html>`
 *   (`branding-theme.ts`) and wins over all of it; a custom device accent
 *   writes `--accent-primary` inline and still wins over the theme's action.
 * - Islands: an element with its own `data-theme` below the root resolves the
 *   theme's flavor for that mode, like the tokens' own dark-island blocks.
 *
 * Generated rules never use `!important` and never set a property outside
 * the catalog's role and variable lists.
 */

import {
  COLOR_THEME_CHANNELS,
  COLOR_THEME_FAMILIES,
  COLOR_THEME_ROLE_PROPERTIES,
  COLOR_THEME_VARIABLE_PROPERTIES,
  type ColorThemeAccentValue,
  type ColorThemeFamily,
  type ColorThemeFlavor,
  type ColorThemeRoleProperty,
} from './color-theme-catalog';

export const COLOR_THEME_STYLESHEET_PATH =
  'src-ui/src/color-themes.generated.css';
export const COLOR_THEME_STARTUP_STYLESHEET_PATH =
  'src-ui/src/color-themes.startup.generated.css';
export const COLOR_THEME_STARTUP_SCRIPT_PATH = 'src-ui/public/startup-theme.js';

export const STARTUP_INDEX_BEGIN =
  '// BEGIN GENERATED COLOR THEMES (npm run gen:color-themes; do not edit)';
export const STARTUP_INDEX_END = '// END GENERATED COLOR THEMES';

const HEADER = `/* GENERATED by \`npm run gen:color-themes\` from
   src-ui/src/lib/color-theme-catalog.ts (renderer: lib/color-theme-css.ts).
   Do not edit; color-theme-artifacts.test.ts fails when this file drifts.
   Selectors and precedence: see the renderer's header comment. */
`;

type Mode = 'dark' | 'light';

interface Scope {
  /** Attribute selectors on the root, beyond the family. */
  readonly root: string;
  /** Mode condition for the root itself. */
  readonly rootMode: string;
  /** The island selector's mode attribute. */
  readonly island: string;
}

function scopeFor(mode: Mode, flavor: ColorThemeFlavor): Scope {
  return mode === 'dark'
    ? {
        root: `[data-color-theme-flavor="${flavor.id}"]`,
        rootMode: ':not([data-theme="light"])',
        island: '[data-theme="dark"]',
      }
    : {
        root: '[data-color-theme-flavor]',
        rootMode: '[data-theme="light"]',
        island: '[data-theme="light"]',
      };
}

function block(selectors: readonly string[], declarations: string[]): string {
  return `${selectors.join(',\n')} {\n${declarations.map((d) => `  ${d};`).join('\n')}\n}\n`;
}

function accentDeclarations(accent: ColorThemeAccentValue): string[] {
  return [
    `--k-action: ${accent.brand}`,
    `--k-action-contrast: ${accent.contrast}`,
    `--k-focus: ${accent.brand}`,
  ];
}

function brandDeclarations(accent: ColorThemeAccentValue): string[] {
  return [
    `--k-brand: ${accent.brand}`,
    `--k-brand-contrast: ${accent.contrast}`,
  ];
}

function roleSelectors(family: string, scope: Scope, extra = ''): string[] {
  const root = `:root[data-color-theme="${family}"]${scope.root}${extra}`;
  return [`${root}${scope.rootMode}`, `${root} ${scope.island}`];
}

function brandSelectors(family: string, scope: Scope, extra = ''): string[] {
  const where = `[data-color-theme="${family}"]${scope.root}${extra}`;
  return [
    `html[data-color-theme]:where(${where}${scope.rootMode})`,
    `html[data-color-theme]:where(${where}) ${scope.island}`,
  ];
}

function channelSelector(
  family: string,
  scope: Scope,
  channel: (typeof COLOR_THEME_CHANNELS)[number],
): string {
  const host =
    channel === 'dev'
      ? ':root.is-dev-build'
      : `:root[data-app-channel="${channel}"]`;
  return `${host}[data-color-theme="${family}"]${scope.root}${scope.rootMode}`;
}

function flavorRules(
  family: ColorThemeFamily,
  flavor: ColorThemeFlavor,
): string {
  const mode = flavor.mode;
  const scope = scopeFor(mode, flavor);
  const fallback = flavor.accents[family.defaultAccent];
  const out: string[] = [
    `/* ${family.label} ${flavor.label} (${mode}) */\n`,
    block(roleSelectors(family.id, scope), [
      ...COLOR_THEME_ROLE_PROPERTIES.map(
        (property) => `${property}: ${flavor.roles[property]}`,
      ),
      ...accentDeclarations(fallback),
      ...COLOR_THEME_VARIABLE_PROPERTIES.map(
        (property) => `${property}: ${flavor.variables[property]}`,
      ),
    ]),
    block(brandSelectors(family.id, scope), brandDeclarations(fallback)),
  ];
  for (const { id } of family.accents) {
    if (id === family.defaultAccent) continue;
    const accent = flavor.accents[id];
    const extra = `[data-color-theme-accent="${id}"]`;
    out.push(
      block(roleSelectors(family.id, scope, extra), accentDeclarations(accent)),
      block(brandSelectors(family.id, scope, extra), brandDeclarations(accent)),
    );
  }
  // Dev before Beta and Nightly, as in index.css: a dev build that also
  // reports a channel shows the channel, there and here.
  for (const channel of COLOR_THEME_CHANNELS) {
    out.push(
      block(
        [channelSelector(family.id, scope, channel)],
        brandDeclarations(flavor.channels[channel]),
      ),
    );
  }
  return out.join('');
}

export function renderColorThemeStylesheet(): string {
  const parts = [HEADER];
  for (const family of COLOR_THEME_FAMILIES) {
    for (const flavor of [family.light, ...family.dark]) {
      parts.push(`\n${flavorRules(family, flavor)}`);
    }
  }
  return parts.join('');
}

/** What the splash paints (`components/startup-screen.css`). */
const STARTUP_ROLES: readonly ColorThemeRoleProperty[] = [
  '--k-bg',
  '--k-panel',
  '--k-line-strong',
  '--k-text',
  '--k-text-muted',
];

/**
 * The splash's subset, plus the focus ring of its recovery button. Same
 * selectors as the full sheet's role rules, so it resolves exactly as the
 * app will.
 */
export function renderColorThemeStartupStylesheet(): string {
  const parts = [HEADER];
  for (const family of COLOR_THEME_FAMILIES) {
    for (const flavor of [family.light, ...family.dark]) {
      const scope = scopeFor(flavor.mode, flavor);
      parts.push(
        `\n/* ${family.label} ${flavor.label} (${flavor.mode}) */\n`,
        block(roleSelectors(family.id, scope), [
          ...STARTUP_ROLES.map(
            (property) => `${property}: ${flavor.roles[property]}`,
          ),
          `--k-focus: ${flavor.accents[family.defaultAccent].brand}`,
        ]),
      );
    }
  }
  return parts.join('');
}

/**
 * The index `startup-theme.js` resolves against: per family, the light
 * canvas, each dark flavor's canvas, the defaults and the accent ids.
 */
export function renderColorThemeStartupIndex(): string {
  const index: Record<string, unknown> = {};
  for (const family of COLOR_THEME_FAMILIES) {
    index[family.id] = {
      light: family.light.roles['--k-bg'],
      dark: Object.fromEntries(
        family.dark.map((flavor) => [flavor.id, flavor.roles['--k-bg']]),
      ),
      defaultDark: family.defaultDarkFlavor,
      accents: family.accents.map((accent) => accent.id),
      defaultAccent: family.defaultAccent,
    };
  }
  // Shaped the way the repository formatter leaves it (a JSON string is
  // never re-wrapped), so `lint:check` and the drift test agree.
  return [
    STARTUP_INDEX_BEGIN,
    '  const COLOR_THEMES = JSON.parse(',
    `    '${JSON.stringify(index)}',`,
    '  );',
    `  ${STARTUP_INDEX_END}`,
  ].join('\n');
}

/** Replace the generated block in the startup script; refuses a script without exactly one. */
export function spliceStartupIndex(script: string, index: string): string {
  const begin = script.indexOf(STARTUP_INDEX_BEGIN);
  const end = script.indexOf(STARTUP_INDEX_END);
  if (
    begin === -1 ||
    end === -1 ||
    end < begin ||
    script.indexOf(STARTUP_INDEX_BEGIN, begin + 1) !== -1
  )
    throw new Error(
      `${COLOR_THEME_STARTUP_SCRIPT_PATH} must contain exactly one generated color-theme block`,
    );
  return (
    script.slice(0, begin) +
    index +
    script.slice(end + STARTUP_INDEX_END.length)
  );
}
